// Optional maintenance command. Normal builds use the checked-in assets.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
if (process.argv.length !== 3 || !process.argv[2].startsWith('--landing=')) throw new Error('EXPLICIT_LANDING_DIRECTORY_REQUIRED');
const landing = pathToFileURL(resolve(process.argv[2].slice('--landing='.length)) + sep);
const output = new URL('../', import.meta.url);
const html = await readFile(new URL('index.html', landing), 'utf8');
const css = await readFile(new URL('liquid-glass.css', landing), 'utf8');
const root = css.match(/^:root\s*\{[^}]+\}/m)?.[0];
const mark = html.match(/<span class="brand-mark"[^>]*>\s*(<svg[\s\S]*?<\/svg>)\s*<\/span>/)?.[1];
if (!root || !mark) throw new Error('Landing brand source not found');
const svg = mark.replace('fill="currentColor"', 'fill="#f4ca73"').replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ');
await writeFile(new URL('assets/mark.svg', output), svg + '\n');
await writeFile(new URL('site-brand.css', output), `/* Generated by scripts/sync-site-brand.mjs from the public landing. */\n${root}\n`);
console.log('Landing palette and original logo copied without changing the source site.');
